import pw from '/app/node_modules/playwright/index.js';
const { chromium } = pw;
const url = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(url, { waitUntil: 'networkidle' });
await p.waitForTimeout(1000);
const out = {};
out.play = await p.evaluate(() => !!document.querySelector('.sv-hero .sv-video .sv-play a'));
out.wrapperLeft = await p.evaluate(() => document.querySelectorAll('.sv-hero').length && !!document.querySelector('.sv-hero-container > .default-content-wrapper'));
await p.click('.sv-hero .sv-video');
await p.waitForTimeout(500);
out.popover = await p.evaluate(() => { const d = document.querySelector('dialog.sv-hero-popover'); return d ? d.querySelector('iframe').src : null; });
await p.keyboard.press('Escape');
await p.waitForTimeout(300);
out.popoverClosed = await p.evaluate(() => !document.querySelector('dialog.sv-hero-popover'));
// trial: empty submit stays, filled navigates
await p.fill('#sv-trial-email', 'a@b.co');
const [req] = await Promise.all([p.waitForRequest((r) => r.url().includes('register'), { timeout: 5000 }).catch(() => null), p.click('.sv-trial-btn')]);
out.trialNav = req ? req.url() : null;
await p.goto(url, { waitUntil: 'networkidle' });
await p.waitForTimeout(800);
await p.evaluate(() => document.querySelector('.sv-quotes').scrollIntoView({ block: 'center' }));
await p.waitForTimeout(600);
out.playing = await p.evaluate(() => document.querySelector('.sv-quotes').classList.contains('is-playing'));
out.anim = await p.evaluate(() => getComputedStyle(document.querySelector('.sv-logo-tab.is-active'), '::before').animationName);
await p.waitForTimeout(10500);
out.afterAutoplay = await p.evaluate(() => [...document.querySelectorAll('.sv-quotes-slide')].findIndex((s) => s.classList.contains('is-active')));
await p.click('.sv-res-nav button[aria-label="Next"]');
await p.waitForTimeout(700);
out.resTransform = await p.evaluate(() => document.querySelector('.sv-res-track').style.transform);
await p.click('.sv-acc-item:nth-child(2) .sv-acc-head');
await p.waitForTimeout(400);
out.acc = await p.evaluate(() => [...document.querySelectorAll('.sv-accm-img')].findIndex((m) => m.classList.contains('is-active')));
out.errs = errs;
console.log(JSON.stringify(out, null, 1));
await b.close();
